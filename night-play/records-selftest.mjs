import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
const data=new Map(),localStorage={getItem:key=>data.get(key)??null,setItem:(key,value)=>data.set(key,value)};
const window={};vm.runInNewContext(readFileSync(new URL('./records.js',import.meta.url),'utf8'),{window,localStorage});
data.set('night-play-history-v1-racing','[10,20]');
window.NightRecords.round('racing',2500);
assert.equal(data.get('night-play-history-count-v1-racing'),'3','migrates existing history count');
assert.equal(data.get('night-play-v1-racing'),'2500');
for(let n=0;n<20;n++)window.NightRecords.round('racing',n);
assert.equal(JSON.parse(data.get('night-play-history-v1-racing')).length,12,'history stays bounded');
assert.equal(data.get('night-play-history-count-v1-racing'),'23','count survives history truncation');
assert.equal(data.get('night-play-v1-racing'),'2500','lower result does not replace best');
data.set('night-play-history-v1-piano-tiles','invalid');
data.set('night-play-history-count-v1-piano-tiles','NaN');
window.NightRecords.round('piano-tiles',125);
assert.equal(data.get('night-play-history-count-v1-piano-tiles'),'1','recovers malformed old records');
const before=JSON.stringify([...data]);
window.NightRecords.round('bad id',100);window.NightRecords.round('racing',NaN);
assert.equal(JSON.stringify([...data]),before,'rejects invalid inputs');
localStorage.setItem=()=>{throw Error('storage unavailable')};
assert.doesNotThrow(()=>window.NightRecords.round('racing',5000),'storage failure cannot break gameplay');
console.log('PASS shared Profile records, migration, retention and unavailable storage');
