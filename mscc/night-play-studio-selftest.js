import assert from 'node:assert/strict'
import { DatabaseSync } from 'node:sqlite'
import { NightPlay } from './night-play.js'
import { NightPlayStudio, StudioAccessError } from './night-play-studio.js'
const db=new DatabaseSync(':memory:')
db.exec('PRAGMA foreign_keys=ON')
const play=new NightPlay(db,{now:()=>1700000000000})
db.prepare('INSERT INTO play_users VALUES (?,?,?)').run('NIGHT-operator','Owner',1700000000000)
db.prepare('INSERT INTO play_users VALUES (?,?,?)').run('NIGHT-visitor','Visitor',1700000000000)
db.prepare('INSERT INTO play_identities VALUES (?,?)').run('2348000000001','NIGHT-operator')
db.prepare('INSERT INTO play_identities VALUES (?,?)').run('2348000000002','NIGHT-visitor')
const guard=new NightPlayStudio(play,{operatorIdentities:'2348000000001'})
assert.equal(guard.isOperator('NIGHT-operator'),true)
assert.equal(guard.isOperator('NIGHT-visitor'),false)
assert.equal(new NightPlayStudio(play,{operatorIdentities:''}).isOperator('NIGHT-operator'),false)
assert.deepEqual(guard.publicNotice(),{enabled:false,revision:0})
assert.throws(()=>guard.status('NIGHT-visitor'),e=>e instanceof StudioAccessError&&e.status===403)
assert.throws(()=>guard.save('NIGHT-visitor',{noticeTitle:'A',noticeMessage:'B',noticeEnabled:true}),e=>e.status===403)
assert.throws(()=>guard.save('NIGHT-operator',{noticeTitle:'A',noticeMessage:'B',noticeEnabled:'true'}),e=>e.status===400)
assert.deepEqual(guard.save('NIGHT-operator',{noticeTitle:'  News  ',noticeMessage:'Fresh updates',noticeEnabled:true}).notice,{title:'News',message:'Fresh updates',enabled:true,revision:1})
assert.equal(guard.save('NIGHT-operator',{noticeTitle:'News',noticeMessage:'Paused',noticeEnabled:false}).notice.revision,2)
assert.equal(guard.publicNotice().enabled,false)
assert.equal(guard.status('NIGHT-operator').authorized,true)
const session='A'.repeat(43)
const crypto=await import('node:crypto')
db.prepare('INSERT INTO play_sessions VALUES (?,?,?)').run(crypto.createHash('sha256').update(session).digest('hex'),'NIGHT-operator',1700000000000+86400000)
const outsider='B'.repeat(43)
db.prepare('INSERT INTO play_sessions VALUES (?,?,?)').run(crypto.createHash('sha256').update(outsider).digest('hex'),'NIGHT-visitor',1700000000000+86400000)
assert.throws(()=>play.request({action:'admin:status',session:outsider}),e=>e.status===403)
assert.throws(()=>play.request({action:'admin:notice:save',session:outsider,noticeTitle:'Hack',noticeMessage:'No',noticeEnabled:true}),e=>e.status===403)
assert.equal(guard.publicNotice().message,'Paused')
assert.equal(play.request({action:'site:notice'}).message,'Paused')
assert.throws(()=>play.request({action:'admin:status',session}),e=>e.status===403)
// The default NightPlay instance denies operator actions until a private allowlist is configured.
assert.equal(play.studio.isOperator('NIGHT-operator'),false)
db.close()
console.log('PASS NIGHT Play Studio: denied-by-default operator access, verified identities, notices and guest read')
